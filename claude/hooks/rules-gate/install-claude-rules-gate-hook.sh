#!/bin/bash
# Installs the Claude Code rules gate for ~/AI-management (v2, 2026-11-25): a session must READ the rule
# files, a declaration is not enough.
#   PostToolUse (Read)             records which reading-list files the session read, by content (git blob id)
#   PreToolUse  (every tool)       refuses every other tool until each listed file is read at its current content
#   SessionStart, UserPromptSubmit print what is unread (after a commit: only the files that changed)
# The list is general/rules/mandatory-repo-read/reading-list.txt, read at run time.
# Only adds hook entries; the guarded rule hook (agent-responsibility-rule.sh) and every other entry are left
# as they are. Backup: ~/.claude/settings.json.bak-rules-gate
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/../../.." && pwd)"
CLAUDE_DIR="${CLAUDE_HOME:-$HOME/.claude}"
mkdir -p "$CLAUDE_DIR/hooks"
H="$CLAUDE_DIR/hooks/ai-management-rules-gate.sh"

cat > "$H" <<'EOF'
#!/bin/bash
# AI-management rules gate v2 (2026-11-25). Generated by claude/hooks/rules-gate/install-claude-rules-gate-hook.sh.
# Arg: SessionStart | UserPromptSubmit | SubagentStart | PreToolUse | PostToolUse | status <claude-session_id>
# It fails open: any internal problem lets the tool call through. AI_MGMT_RULES_GATE_OFF=1 is the user's off
# switch; an agent never sets it.
mode="${1:-SessionStart}"
status_id="${2:-}"
REPO="@REPO@"
LIST="$REPO/general/rules/mandatory-repo-read/reading-list.txt"
STATE="${AI_MGMT_READ_DIR:-$HOME/.ai-management/rules-read}"
ACK_DIR="${AI_MGMT_ACK_DIR:-$HOME/.ai-management/rules-ack}"
CLAUDE_MD="${CLAUDE_HOME:-$HOME/.claude}/CLAUDE.md"

if [ "$mode" = status ]; then input=""; else input="$(cat 2>/dev/null || true)"; fi
[ "${AI_MGMT_RULES_GATE_OFF:-0}" = 1 ] && exit 0
[ "$mode" = SubagentStart ] && exit 0          # a subagent rides on its session's record
command -v jq >/dev/null 2>&1 || exit 0
[ -r "$LIST" ] || exit 0

sid=""; agent=""; tool=""; fp=""; off=0; lim=0
if [ "$mode" = status ]; then
  safe="$(printf '%s' "$status_id" | tr -cd 'A-Za-z0-9._-')"
else
  IFS=$'\037' read -r sid agent tool fp off lim <<< "$(printf '%s' "$input" | jq -r '[.session_id // "", .agent_id // "", .tool_name // "", (.tool_input.file_path // "" | tostring), (.tool_input.offset // 0 | tostring), (.tool_input.limit // 0 | tostring)] | join("\u001f")' 2>/dev/null)"
  [ -n "$sid" ] || exit 0
  case "$sid" in *[!A-Za-z0-9._-]*) sid="$(printf '%s' "$sid" | tr -cd 'A-Za-z0-9._-')" ;; esac
  safe="claude-$sid"
fi
[ -n "$safe" ] || exit 0
mkdir -p "$STATE" 2>/dev/null || exit 0
rec="$STATE/$safe"
ok="$rec.ok"

# The reading list for this platform.
case "$OSTYPE" in darwin*) plat=darwin ;; *) plat=linux ;; esac
paths=()
while IFS= read -r line || [ -n "$line" ]; do
  line="${line%%#*}"
  set -f; set -- $line; set +f
  case $# in
    1) paths+=("$1") ;;
    2) [ "$1" = "$plat" ] && paths+=("$2") ;;
  esac
done < "$LIST"
[ "${#paths[@]}" -gt 0 ] || exit 0

missing=()   # listed files this session has not read at their current content
changed=()   # those of them it read before, at an older content

fresh() {    # 0 when the session was complete and nothing on the list changed since
  [ -f "$ok" ] || return 1
  [ "$LIST" -nt "$ok" ] && return 1
  local p
  for p in "${paths[@]}"; do [ "$REPO/$p" -nt "$ok" ] && return 1; done
  return 0
}

compute() {  # fills missing[] and changed[]; 2 when the files cannot be hashed
  missing=(); changed=()
  local exist=() p ids id i=0
  for p in "${paths[@]}"; do [ -f "$REPO/$p" ] && exist+=("$p"); done
  [ "${#exist[@]}" -gt 0 ] || return 0
  ids="$(cd "$REPO" 2>/dev/null && git hash-object -- "${exist[@]}" 2>/dev/null)" || return 2
  [ -n "$ids" ] || return 2
  while IFS= read -r id; do
    p="${exist[$i]}"; i=$((i + 1))
    if ! grep -qxF "$id	$p" "$rec" 2>/dev/null; then
      missing+=("$p")
      grep -qF "	$p" "$rec" 2>/dev/null && changed+=("$p")
    fi
  done <<< "$ids"
  [ "$i" -eq "${#exist[@]}" ] || return 2
  return 0
}

gate_state() {  # 0 open, 1 closed (missing[] is filled), 2 cannot tell
  fresh && return 0
  local tmpok="$ok.$$" head
  : > "$tmpok" 2>/dev/null
  compute || { rm -f "$tmpok"; return 2; }
  if [ "${#missing[@]}" -eq 0 ]; then
    mv -f "$tmpok" "$ok" 2>/dev/null
    head="$(git -C "$REPO" rev-parse HEAD 2>/dev/null)" || head=""
    if [ -n "$head" ] && mkdir -p "$ACK_DIR" 2>/dev/null; then printf '%s\n' "$head" > "$ACK_DIR/$safe" 2>/dev/null; fi
    return 0
  fi
  rm -f "$tmpok" "$ok"
  return 1
}

unread_lines() {
  local p
  for p in "${missing[@]}"; do
    case " ${changed[*]} " in
      *" $p "*) printf '\n- %s (changed since you read it)' "$REPO/$p" ;;
      *) printf '\n- %s' "$REPO/$p" ;;
    esac
  done
}

case "$mode" in
  PostToolUse)
    [ "$tool" = Read ] || exit 0
    [ -n "$agent" ] && exit 0                  # a subagent's read is not the session's read
    for p in "${paths[@]}"; do
      [ "$fp" = "$REPO/$p" ] || continue
      case "$off" in ''|*[!0-9]*) off=0 ;; esac
      case "$lim" in ''|*[!0-9]*) lim=0 ;; esac
      n="$(wc -l < "$fp" 2>/dev/null | tr -d ' ')"; n="${n:-0}"
      if [ "$off" -le 1 ] && { [ "$lim" -eq 0 ] || [ "$lim" -ge "$n" ]; }; then      # the whole file only
        id="$(git hash-object -- "$fp" 2>/dev/null)" || id=""
        [ -n "$id" ] && printf '%s\t%s\n' "$id" "$p" >> "$rec"
      fi
      break
    done
    exit 0
    ;;
  PreToolUse)
    [ -n "$agent" ] && exit 0
    gate_state; st=$?
    [ "$st" -eq 1 ] || exit 0
    if [ "$tool" = Read ]; then
      [ "$fp" = "$CLAUDE_MD" ] && exit 0
      for p in "${paths[@]}"; do [ "$fp" = "$REPO/$p" ] && exit 0; done
    fi
    reason="Refused by the AI-management rules gate (the user, 2026-11-24: every session reads the repository's rules before it works). Read these ${#missing[@]} file(s) with the Read tool, each whole (no offset, no limit); one batch is fine. Every other tool is refused until then. The hook records the reads; there is no command to run.$(unread_lines)"
    jq -n --arg r "$reason" '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$r}}'
    exit 0
    ;;
  SessionStart|UserPromptSubmit)
    gate_state; st=$?
    [ "$st" -eq 1 ] || exit 0
    note="[AI-MANAGEMENT RULES GATE] This session has not read ${#missing[@]} of the ${#paths[@]} rule files in $REPO at their current content. Read each with the Read tool, whole (no offset, no limit), before anything else; every other tool is refused until then. The hook records the reads; there is no command to run.$(unread_lines)
Two rules from these files that sessions have broken:
- A download the user will run is delivered as a script copied and adapted from $REPO/general/templates/download-ui/fetch_dst.py and download_wrapper.sh (in-place dashboard, narrow layout below 100 columns, status subcommand, resume, verification, single-instance guard, exit codes 0/1/2/3); never an improvised downloader.
- When the user has to run something, the complete copy-paste command is the last thing in your closing message (Rule 14)."
    jq -n --arg e "$mode" --arg n "$note" '{hookSpecificOutput:{hookEventName:$e, additionalContext:$n}}'
    exit 0
    ;;
  status)
    gate_state; st=$?
    if [ "$st" -eq 2 ]; then echo "$safe: cannot check (git or the reading list is unavailable)"; exit 2; fi
    [ "$st" -eq 0 ] && missing=()
    echo "$safe: read $(( ${#paths[@]} - ${#missing[@]} )) of ${#paths[@]}"
    for p in "${missing[@]}"; do echo "  unread: $p"; done
    exit "$st"
    ;;
esac
exit 0
EOF

sed -i.sedbak -e "s|@REPO@|$REPO|g" "$H" && rm -f "$H.sedbak"
chmod +x "$H"
bash -n "$H"

# Wire the five events; an entry that is already there is left alone.
S="$CLAUDE_DIR/settings.json"
[ -f "$S" ] || echo '{}' > "$S"
jq '
  def cmd(e): ("\"$HOME/.claude/hooks/ai-management-rules-gate.sh\" " + e);
  def wired(ev): any((.hooks[ev] // [])[]?.hooks[]?; .command == cmd(ev));
  def add(ev; entry): if wired(ev) then . else .hooks[ev] = ((.hooks[ev] // []) + [entry]) end;
  def plain(ev): {hooks:[{type:"command",command:cmd(ev),timeout:10}]};
  .hooks = (.hooks // {})
  | add("SessionStart"; plain("SessionStart"))
  | add("SubagentStart"; plain("SubagentStart"))
  | add("UserPromptSubmit"; plain("UserPromptSubmit"))
  | add("PreToolUse"; plain("PreToolUse"))
  | add("PostToolUse"; (plain("PostToolUse") + {matcher:"Read"}))
' "$S" > "$S.new"
jq empty "$S.new"
if cmp -s "$S" "$S.new"; then
  rm -f "$S.new"
  echo "updated script $H (already wired in $S)"
else
  cp -p "$S" "$S.bak-rules-gate"
  mv "$S.new" "$S"
  echo "installed: $H, wired into $S (backup $S.bak-rules-gate)"
fi

# Self-test in a throwaway state directory: refused until every listed file is read whole, then open.
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
gate() { AI_MGMT_READ_DIR="$T/read" AI_MGMT_ACK_DIR="$T/ack" "$H" "$@"; }
call() { jq -n --arg t "$1" --arg f "${2:-}" --argjson l "${3:-0}" --arg a "${4:-}" \
  '{session_id:"install-test", tool_name:$t, tool_input:({file_path:$f} + (if $l > 0 then {limit:$l} else {} end))} + (if $a != "" then {agent_id:$a} else {} end)'; }
denied() { jq -e '.hookSpecificOutput.permissionDecision == "deny"' >/dev/null; }

case "$OSTYPE" in darwin*) plat=darwin ;; *) plat=linux ;; esac
listed=()
while IFS= read -r line || [ -n "$line" ]; do
  line="${line%%#*}"; set -f; set -- $line; set +f
  case $# in 1) listed+=("$1") ;; 2) [ "$1" = "$plat" ] && listed+=("$2") ;; esac
done < "$REPO/general/rules/mandatory-repo-read/reading-list.txt"
first="$REPO/${listed[0]}"

call Bash | gate PreToolUse | denied                                   # nothing read: a tool is refused
[ -z "$(call Read "$first" | gate PreToolUse)" ]                       # reading a listed file is allowed
[ -z "$(call Read "$CLAUDE_DIR/CLAUDE.md" | gate PreToolUse)" ]        # and so is reading CLAUDE.md
call Read "$REPO/install-all.sh" | gate PreToolUse | denied            # another file is not
[ -z "$(call Bash "" 0 sub-1 | gate PreToolUse)" ]                     # a subagent rides on its session
call Read "$first" 3 | gate PostToolUse                                # three lines are not the file
call Read "$first" 0 sub-1 | gate PostToolUse                          # a subagent's read is not the session's
[ ! -s "$T/read/claude-install-test" ]
for p in "${listed[@]}"; do call Read "$REPO/$p" | gate PostToolUse; done
[ -z "$(call Bash | gate PreToolUse)" ]                                # everything read: open
[ -z "$(echo '{"session_id":"install-test"}' | gate UserPromptSubmit)" ]
gate status claude-install-test >/dev/null
echo '{"session_id":"install-test-2"}' | gate SessionStart | jq -e '.hookSpecificOutput.additionalContext | contains("AI-MANAGEMENT RULES GATE")' >/dev/null
echo "self-test passed: $H"
